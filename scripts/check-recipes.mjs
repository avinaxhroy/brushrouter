#!/usr/bin/env node
// Integrity check for data/recipes/.
//
// This is the invariant that makes the recipe library usable at all. A recipe is
// a template: if it references a slot it does not declare, or declares one it
// never uses, the generated prompt ships with a literal "{ratio}" left in it and
// the agent sends that to the image model. Cheap to check, expensive to miss.
//
// Exported so tests/recipes.test.js can assert it, and runnable as a CLI:
//   node scripts/check-recipes.mjs

import { readFileSync, readdirSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";

export const RECIPES_DIR = fileURLToPath(new URL("../data/recipes/", import.meta.url));
export const STYLES_FILE = fileURLToPath(new URL("../data/styles/styles.json", import.meta.url));

// A malformed recipe file is a real failure mode and the raw SyntaxError says
// nothing about which file broke. Report the path instead.
function readJson(path) {
  let raw;
  try {
    raw = readFileSync(path, "utf8");
  } catch (cause) {
    throw new Error(`cannot read recipe file ${path}: ${cause.message}`, { cause });
  }
  try {
    return JSON.parse(raw);
  } catch (cause) {
    throw new Error(`invalid JSON in ${path}: ${cause.message}`, { cause });
  }
}

export function validateRecipes(dir = RECIPES_DIR) {
  const slots = readJson(`${dir}slots.json`);
  const names = new Set(Object.keys(slots.slots));
  const problems = [];
  const stats = { categories: 0, recipes: 0, image: 0, shapes: {} };

  // Read every category first: duplicate ids can only be seen across files.
  const docs = readdirSync(dir)
    .filter((f) => f.endsWith(".json") && f !== "slots.json")
    .map((f) => [f, readJson(`${dir}${f}`)]);
  const seenRecipeIds = new Set();

  for (const [f, c] of docs) {
    stats.categories++;
    if (c.id !== f.replace(/\.json$/, "")) problems.push(`${f}: id "${c.id}" does not match the filename`);
    if (!c.aliases?.length) problems.push(`${c.id}: no aliases, so it cannot be searched for`);
    if (!c.intent) problems.push(`${c.id}: no intent line`);
    // Every recipe needs an id: `listCategories` maps a category's recipes to
    // ids and then looks each one back up, and `--id`/`findRecipes` search by
    // id. A recipe without one is silently unreachable (and used to make the
    // shape lookup throw on undefined).
    for (const r of c.recipes || []) {
      if (!r.id || typeof r.id !== "string") problems.push(`${c.id}: a recipe has no id`);
      stats.recipes++;
      stats.shapes[r.shape] = (stats.shapes[r.shape] || 0) + 1;
      if (r.image) stats.image++;
      if (seenRecipeIds.has(r.id)) problems.push(`${r.id}: duplicate recipe id`);
      seenRecipeIds.add(r.id);

      const check = (s, where) => {
        for (const m of s.matchAll(/\{(\w+)\}/g)) {
          const k = m[1];
          // Every placeholder must be declared, free slots included: `slots[]` is
          // what the agent is shown (publicRecipe, the "Slots:" line), so a
          // skeleton placeholder missing from it is a contract mismatch — that
          // is how `{subject}` stayed invisible on 24 recipes.
          if (!names.has(k)) problems.push(`${r.id} ${where}: unknown slot {${k}}`);
          else if (!r.slots.includes(k)) problems.push(`${r.id} ${where}: {${k}} used but not declared in slots[]`);
        }
      };
      check(r.text, "text");
      if (r.image) check(r.image.skeleton, "image");

      for (const s of r.slots) {
        if (!names.has(s)) problems.push(`${r.id}: declares unknown slot ${s}`);
        else if (!r.text.includes(`{${s}}`) && !(r.image?.skeleton || "").includes(`{${s}}`)) {
          problems.push(`${r.id}: declares ${s} but never uses it`);
        }
      }
      for (const [k, v] of Object.entries(r.defaults || {})) {
        if (!r.slots.includes(k)) problems.push(`${r.id}: default for undeclared slot ${k}`);
        else if (!slots.slots[k].options.includes(v)) problems.push(`${r.id}: default ${k}="${v}" is not one of the offered options`);
      }
      if (!slots.shapes[r.shape]) problems.push(`${r.id}: unknown shape "${r.shape}"`);
      if (!r.negatives?.length) problems.push(`${r.id}: no negatives`);
      if (!r.example) problems.push(`${r.id}: no example`);
      if (r.image && !r.image.preserve?.length) problems.push(`${r.id}: has an image path but nothing listed to preserve`);
      if (r.image && !r.image.accepts) problems.push(`${r.id}: has an image path but does not say what it accepts`);
    }
  }
  return { ok: problems.length === 0, problems, stats };
}

// The vendored looks are generated by scripts/vendor-styles.mjs, but a generated
// file still gets hand-edited, and the failure mode is the same as for recipes: a
// placeholder the caller never fills reaches the image model verbatim. Absent
// looks are legitimate — the library runs jobs-only without them — but a
// malformed file is not, so readJson is left to throw.
export function validateStyles(file = STYLES_FILE) {
  if (!existsSync(file)) return { ok: true, problems: [], stats: { styles: 0, categories: 0, present: false } };
  const doc = readJson(file);
  const styles = doc.styles || [];
  const problems = [];
  const stats = { styles: styles.length, categories: (doc.categories || []).length, present: true, slots: {} };

  if (!/^[a-f0-9]{64}$/.test(String(doc.stylesSha256 || ""))) problems.push("styles.json: missing or malformed stylesSha256");
  for (const k of ["repo", "commit", "license", "copyright"]) {
    if (!doc.source?.[k]) problems.push(`styles.json: source.${k} is required for attribution`);
  }

  // Promoted to fields, so they must not survive as template placeholders.
  const promoted = new Set(["style_fidelity_anchors", "source_content_to_avoid", "negative_prompt"]);
  for (const s of styles) {
    if (s.kind !== "look") problems.push(`${s.id}: kind must be "look"`);
    if (!s.text?.length) problems.push(`${s.id}: no text skeleton`);
    if (!s.styleLock?.length) problems.push(`${s.id}: no styleLock, so nothing keeps the look on-model`);
    if (!s.doNotClone?.length) problems.push(`${s.id}: no doNotClone, so the source content is unprotected`);
    if (!s.negatives?.length) problems.push(`${s.id}: no negatives`);
    if (!s.category) problems.push(`${s.id}: no category`);
    if (!s.source?.license || !s.source?.copyright) problems.push(`${s.id}: no attribution`);

    const used = [...s.text.matchAll(/\{(\w+)\}/g)].map((m) => m[1]);
    for (const k of used) {
      if (/^\d+$/.test(k)) problems.push(`${s.id}: numeric placeholder {${k}} left in the template`);
      else if (promoted.has(k)) problems.push(`${s.id}: {${k}} was promoted to a field but is still in the template`);
      else if (!s.slots.includes(k)) problems.push(`${s.id}: {${k}} used but not declared in slots[]`);
    }
    for (const k of s.slots) {
      if (!used.includes(k)) problems.push(`${s.id}: declares ${k} but never uses it`);
      stats.slots[k] = (stats.slots[k] || 0) + 1;
    }
  }
  return { ok: problems.length === 0, problems, stats };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const recipes = validateRecipes();
  const looks = validateStyles();
  console.log(
    `${recipes.stats.categories} categories · ${recipes.stats.recipes} recipes · ${recipes.stats.image} accept a reference image · ` +
      `${recipes.stats.recipes - recipes.stats.image} text-only · shapes ${JSON.stringify(recipes.stats.shapes)}`,
  );
  console.log(
    looks.stats.present
      ? `${looks.stats.styles} vendored looks · ${looks.stats.categories} categories`
      : "no vendored looks (data/styles/styles.json absent) — jobs-only library",
  );
  const problems = [...recipes.problems, ...looks.problems];
  if (problems.length) {
    console.error(`\n${problems.length} problem(s):\n  ${problems.join("\n  ")}`);
    process.exit(1);
  }
  console.log("all recipe and look files valid");
}
